-- 3.1 VIEW: Danh sách cầu thủ khỏe mạnh sẵn sàng thi đấu
CREATE OR REPLACE VIEW view_active_squad AS
SELECT id, full_name, position, jersey_number, ovr, goals, assists, health_status
FROM players
WHERE health_status = 'Fit'
WITH READ ONLY;

-- 3.2 TRIGGER: Tự động cộng dồn bàn thắng/kiến tạo khi có sự kiện trận đấu (Có dùng IF)
CREATE OR REPLACE TRIGGER trg_after_match_event
AFTER INSERT ON match_events
FOR EACH ROW
BEGIN
    IF :NEW.event_type = 'Goal' THEN
        UPDATE players SET goals = goals + 1, updated_at = CURRENT_TIMESTAMP WHERE id = :NEW.player_id;
    ELSIF :NEW.event_type = 'Assist' THEN
        UPDATE players SET assists = assists + 1, updated_at = CURRENT_TIMESTAMP WHERE id = :NEW.player_id;
    ELSIF :NEW.event_type = 'MVP' THEN
        UPDATE players SET mvp = mvp + 1, updated_at = CURRENT_TIMESTAMP WHERE id = :NEW.player_id;
    END IF;
END;
/

-- 3.3 TRIGGER: Tự động cập nhật thời gian updated_at trước khi sửa thông tin
