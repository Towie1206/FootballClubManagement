-- 3.4 PACKAGE: Quản trị nghiệp vụ đội bóng (Có dùng IF-THEN-ELSE, FOR LOOP, WHILE LOOP)
CREATE OR REPLACE PACKAGE pkg_fc_manager IS
    FUNCTION get_top_scorer RETURN VARCHAR2;
    PROCEDURE evaluate_squad_fitness;
    PROCEDURE simulate_training_camp(p_duration_days IN NUMBER);
END pkg_fc_manager;
/

CREATE OR REPLACE PACKAGE BODY pkg_fc_manager IS

    -- Function: Tìm cầu thủ ghi nhiều bàn nhất đội
    FUNCTION get_top_scorer RETURN VARCHAR2 IS
        v_name VARCHAR2(100);
        v_goals NUMBER;
    BEGIN
        SELECT full_name, goals INTO v_name, v_goals 
        FROM players 
        ORDER BY goals DESC 
        FETCH FIRST 1 ROWS ONLY;
        
        IF v_goals = 0 THEN
            RETURN 'Chưa có bàn thắng nào';
        ELSE
            RETURN v_name || ' (' || v_goals || ' bàn thắng)';
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 'Danh sách rỗng';
    END get_top_scorer;

    -- Procedure 1: Đánh giá phân hạng cầu thủ bằng Cursor FOR LOOP và IF-ELSE
    PROCEDURE evaluate_squad_fitness IS
    BEGIN
        DBMS_OUTPUT.PUT_LINE('=== BÁO CÁO PHÂN HẠNG CẦU THỦ TOÀN ĐỘI ===');
        FOR player_rec IN (SELECT full_name, ovr, health_status FROM players) LOOP
            IF player_rec.health_status != 'Fit' THEN
                DBMS_OUTPUT.PUT_LINE('[-] ' || player_rec.full_name || ': Đang chấn thương (Cần chăm sóc y tế)');
            ELSIF player_rec.ovr >= 84 THEN
                DBMS_OUTPUT.PUT_LINE('[*] ' || player_rec.full_name || ': Ngôi sao đẳng cấp (Star Player)');
            ELSIF player_rec.ovr >= 80 THEN
                DBMS_OUTPUT.PUT_LINE('[+] ' || player_rec.full_name || ': Trụ cột chính thức (Key Starter)');
            ELSE
                DBMS_OUTPUT.PUT_LINE('[ ] ' || player_rec.full_name || ': Cầu thủ dự bị chiến lược');
            END IF;
        END LOOP;
    END evaluate_squad_fitness;

    -- Procedure 2: Mô phỏng chuỗi ngày tập huấn chuyên sâu bằng WHILE LOOP
    PROCEDURE simulate_training_camp(p_duration_days IN NUMBER) IS
        v_day NUMBER := 1;
    BEGIN
        DBMS_OUTPUT.PUT_LINE('Mô phỏng đợt tập huấn ' || p_duration_days || ' ngày:');
        WHILE v_day <= p_duration_days LOOP
            INSERT INTO training_sessions(session_date, focus_area, duration_minutes)
            VALUES (SYSDATE + v_day, 'Tập huấn chuyên sâu ngày ' || v_day, 120);
            v_day := v_day + 1;
        END LOOP;
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Hoàn thành tạo lịch tập huấn thành công!');
    END simulate_training_camp;

END pkg_fc_manager;
/

