-- 4.1 VIEW: Danh sách cầu thủ khỏe mạnh sẵn sàng thi đấu
CREATE OR REPLACE VIEW view_active_squad AS
SELECT id, full_name, position, jersey_number, ovr, goals, assists, health_status
FROM players
WHERE health_status = 'Fit'
WITH READ ONLY;

-- 4.2 VIEW: Bảng xếp hạng ghi bàn (Top Scorers)
CREATE OR REPLACE VIEW v_top_scorers AS
SELECT id AS player_id, full_name, position, club, goals, assists, matches
FROM players
WHERE goals > 0
ORDER BY goals DESC, assists DESC;

-- 4.3 VIEW: Bảng tổng kết kết quả thi đấu (Match Summary)
CREATE OR REPLACE VIEW v_match_summary AS
SELECT match_id, match_date, opponent_team, venue, match_type,
       home_score || ' - ' || away_score AS final_score,
       CASE 
           WHEN home_score > away_score THEN 'Thắng (Win)'
           WHEN home_score < away_score THEN 'Thua (Loss)'
           ELSE 'Hòa (Draw)'
       END AS result
FROM matches;

-- 4.4 STANDALONE FUNCTION: Đánh giá phong độ cầu thủ (Có dùng IF-ELSIF-ELSE)
CREATE OR REPLACE FUNCTION get_player_form(p_player_id IN NUMBER) RETURN VARCHAR2 IS
    v_goals NUMBER := 0;
    v_assists NUMBER := 0;
    v_rating VARCHAR2(50);
BEGIN
    SELECT goals, assists INTO v_goals, v_assists FROM players WHERE id = p_player_id;
    IF (v_goals + v_assists) >= 10 THEN
        v_rating := 'Phong độ xuất sắc (World Class)';
    ELSIF (v_goals + v_assists) >= 5 THEN
        v_rating := 'Phong độ ổn định (Good)';
    ELSE
        v_rating := 'Cần cải thiện (Normal)';
    END IF;
    RETURN v_rating;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Không tìm thấy cầu thủ';
END get_player_form;
/

-- 4.5 STANDALONE PROCEDURE: Báo cáo kết quả tập luyện (Có dùng FOR LOOP)
CREATE OR REPLACE PROCEDURE generate_training_report IS
BEGIN
    DBMS_OUTPUT.PUT_LINE('--- BÁO CÁO ĐÁNH GIÁ TẬP LUYỆN TOÀN ĐỘI ---');
    FOR rec IN (
        SELECT p.full_name, ts.focus_area, pt.performance_rating
        FROM player_training pt
        JOIN players p ON pt.player_id = p.id
        JOIN training_sessions ts ON pt.session_id = ts.session_id
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('Cầu thủ: ' || rec.full_name || ' | Bài tập: ' || rec.focus_area || ' | Điểm: ' || rec.performance_rating);
    END LOOP;
END generate_training_report;
/

-- 4.6 TRIGGER 1: Tự động cập nhật bàn thắng, kiến tạo, MVP vào hồ sơ cầu thủ
CREATE OR REPLACE TRIGGER trg_after_match_event
AFTER INSERT ON match_events
FOR EACH ROW
BEGIN
    IF :NEW.event_type = 'Goal' THEN
        UPDATE players SET goals = goals + 1, updated_at = CURRENT_TIMESTAMP WHERE id = :NEW.player_id;
    ELSIF :NEW.event_type = 'Assist' THEN
        UPDATE players SET assists = assists + 1, updated_at = CURRENT_TIMESTAMP WHERE id = :NEW.player_id;
    ELSIF :NEW.event_type = 'MVP' THEN
        UPDATE players SET mvp = mvp + 1, updated_at = CURRENT_TIMESTAMP WHERE id = :NEW.player_id;
    END IF;
END;
/

-- 4.7 TRIGGER 2: Tự động cập nhật thời gian updated_at trước khi sửa cầu thủ
CREATE OR REPLACE TRIGGER trg_update_timestamp
BEFORE UPDATE ON players
FOR EACH ROW
BEGIN
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
