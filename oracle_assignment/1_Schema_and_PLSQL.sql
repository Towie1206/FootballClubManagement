-- 4.8 PACKAGE SPECIFICATION: Khai báo Package quản trị đội bóng FC Manager
CREATE OR REPLACE PACKAGE pkg_fc_manager IS
    FUNCTION get_top_scorer RETURN VARCHAR2;
    PROCEDURE evaluate_squad_fitness;
    PROCEDURE simulate_training_camp(p_duration_days IN NUMBER);
END pkg_fc_manager;
/

-- 4.9 PACKAGE BODY: Hiện thực Package (Có dùng IF, FOR LOOP, WHILE LOOP)
CREATE OR REPLACE PACKAGE BODY pkg_fc_manager IS

    -- Function: Tìm vua phá lưới của đội (Dùng IF và FETCH FIRST)
    FUNCTION get_top_scorer RETURN VARCHAR2 IS
        v_name VARCHAR2(100);
        v_goals NUMBER;
    BEGIN
        SELECT full_name, goals INTO v_name, v_goals 
        FROM players 
        ORDER BY goals DESC 
        FETCH FIRST 1 ROWS ONLY;
        
        IF v_goals = 0 THEN
            RETURN 'Chưa có bàn thắng nào';
        ELSE
            RETURN v_name || ' (' || v_goals || ' bàn thắng)';
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 'Danh sách cầu thủ rỗng';
    END get_top_scorer;

    -- Procedure 1: Đánh giá phân hạng thể lực cầu thủ (Dùng Cursor FOR LOOP VÀ IF-ELSIF)
    PROCEDURE evaluate_squad_fitness IS
    BEGIN
        DBMS_OUTPUT.PUT_LINE('====================================================');
        DBMS_OUTPUT.PUT_LINE('       BÁO CÁO ĐÁNH GIÁ THỂ LỰC VÀ ĐỘI HÌNH CLB     ');
        DBMS_OUTPUT.PUT_LINE('====================================================');
        FOR player_rec IN (SELECT full_name, ovr, health_status FROM players ORDER BY ovr DESC) LOOP
            IF player_rec.health_status != 'Fit' THEN
                DBMS_OUTPUT.PUT_LINE('[-] ' || RPAD(player_rec.full_name, 22) || ': ĐANG CHẤN THƯƠNG (Cần chăm sóc y tế)');
            ELSIF player_rec.ovr >= 84 THEN
                DBMS_OUTPUT.PUT_LINE('[*] ' || RPAD(player_rec.full_name, 22) || ': NGÔI SAO ĐẲNG CẤP (Star Player)');
            ELSIF player_rec.ovr >= 80 THEN
                DBMS_OUTPUT.PUT_LINE('[+] ' || RPAD(player_rec.full_name, 22) || ': TRỤ CỘT CHÍNH THỨC (Key Starter)');
            ELSE
                DBMS_OUTPUT.PUT_LINE('[ ] ' || RPAD(player_rec.full_name, 22) || ': CẦU THỦ DỰ BỊ CHIẾN LƯỢC');
            END IF;
        END LOOP;
        DBMS_OUTPUT.PUT_LINE('====================================================');
    END evaluate_squad_fitness;

    -- Procedure 2: Mô phỏng chuỗi ngày tập huấn chuyên sâu (Dùng WHILE LOOP)
    PROCEDURE simulate_training_camp(p_duration_days IN NUMBER) IS
        v_day NUMBER := 1;
    BEGIN
        DBMS_OUTPUT.PUT_LINE('Mô phỏng đợt tập huấn ' || p_duration_days || ' ngày:');
        WHILE v_day <= p_duration_days LOOP
            INSERT INTO training_sessions(session_date, focus_area, duration_minutes)
            VALUES (SYSDATE + v_day, 'Tập huấn chuyên sâu ngày ' || v_day, 120);
            v_day := v_day + 1;
        END LOOP;
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Hoàn thành tạo lịch tập huấn thành công!');
    END simulate_training_camp;

END pkg_fc_manager;
/

