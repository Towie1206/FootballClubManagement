DECLARE
    table_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO table_count FROM user_tables WHERE table_name = 'SCHEMA_MIGRATIONS';
    IF table_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE schema_migrations (
                version VARCHAR2(64) PRIMARY KEY,
                applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
            )';
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_players_ovr_and_timestamp
BEFORE INSERT OR UPDATE ON players
FOR EACH ROW
BEGIN
    IF INSERTING
       OR :NEW.pac <> :OLD.pac OR :NEW.sho <> :OLD.sho OR :NEW.pas <> :OLD.pas
       OR :NEW.dri <> :OLD.dri OR :NEW.def <> :OLD.def OR :NEW.phy <> :OLD.phy THEN
        :NEW.ovr := TRUNC((:NEW.pac + :NEW.sho + :NEW.pas + :NEW.dri + :NEW.def + :NEW.phy) / 6);
    END IF;
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

