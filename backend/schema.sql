-- 1. Tạo bảng Cầu thủ (Players)
CREATE TABLE Players (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullName VARCHAR2(100) NOT NULL,
    position VARCHAR2(10) NOT NULL,
    jerseyNumber NUMBER(3) NOT NULL,
    healthStatus VARCHAR2(50) DEFAULT 'Fit',
    ovr NUMBER(3) DEFAULT 50,
    goals NUMBER(4) DEFAULT 0,
    mvp NUMBER(4) DEFAULT 0
);

