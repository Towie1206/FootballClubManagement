-- 3. Tạo Trigger tự động cập nhật OVR (Ví dụ nâng cao ăn điểm CSDL)
-- Nếu ghi được nhiều bàn thắng hoặc MVP thì tự động tăng OVR.
CREATE OR REPLACE TRIGGER trg_UpdateOVR
BEFORE UPDATE ON Players
FOR EACH ROW
BEGIN
    IF :NEW.goals > :OLD.goals THEN
        :NEW.ovr := :NEW.ovr + 1;
    END IF;
END;
