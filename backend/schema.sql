MERGE INTO players target
USING (
    SELECT 'Lionel Messi' full_name, 'FW' position, 10 jersey_number, 92 pac, 95 sho, 91 pas, 96 dri, 38 def, 65 phy FROM dual
    UNION ALL
    SELECT 'Kevin De Bruyne', 'MF', 17, 76, 89, 94, 88, 65, 78 FROM dual
    UNION ALL
    SELECT 'Virgil van Dijk', 'DF', 4, 78, 60, 71, 72, 92, 90 FROM dual
    UNION ALL
    SELECT 'Alisson Becker', 'GK', 1, 65, 40, 70, 60, 45, 82 FROM dual
) source
ON (target.jersey_number = source.jersey_number)
WHEN NOT MATCHED THEN INSERT (
    full_name, position, jersey_number, health_status, matches, goals, assists, mvp,
    club, pac, sho, pas, dri, def, phy
) VALUES (
    source.full_name, source.position, source.jersey_number, 'Fit', 0, 0, 0, 0,
    'FC Manager', source.pac, source.sho, source.pas, source.dri, source.def, source.phy
);

MERGE INTO schema_migrations target
USING (SELECT '20260901_backend_hardening' version FROM dual) source
ON (target.version = source.version)
WHEN NOT MATCHED THEN INSERT (version) VALUES (source.version);

COMMIT;
