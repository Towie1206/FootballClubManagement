-- Football Club Management - Oracle schema/migration
-- This script is non-destructive: it creates missing objects and upgrades the
-- original camelCase Players table without dropping existing rows.

SET DEFINE OFF;

DECLARE
    table_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO table_count FROM user_tables WHERE table_name = 'PLAYERS';
    IF table_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE players (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name VARCHAR2(100) NOT NULL,
                position VARCHAR2(2) NOT NULL,
                jersey_number NUMBER(3) NOT NULL,
                health_status VARCHAR2(20) DEFAULT ''Fit'' NOT NULL,
                ovr NUMBER(3) DEFAULT 70 NOT NULL,
                matches NUMBER(7) DEFAULT 0 NOT NULL,
                goals NUMBER(7) DEFAULT 0 NOT NULL,
                assists NUMBER(7) DEFAULT 0 NOT NULL,
                mvp NUMBER(7) DEFAULT 0 NOT NULL,
                club VARCHAR2(100) DEFAULT ''Tự do'' NOT NULL,
                pac NUMBER(3) DEFAULT 70 NOT NULL,
                sho NUMBER(3) DEFAULT 70 NOT NULL,
                pas NUMBER(3) DEFAULT 70 NOT NULL,
                dri NUMBER(3) DEFAULT 70 NOT NULL,
                def NUMBER(3) DEFAULT 70 NOT NULL,
                phy NUMBER(3) DEFAULT 70 NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
            )';
    END IF;
END;
/

-- Upgrade column names from the first version of the assignment schema.
DECLARE
    old_count NUMBER;
    new_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO old_count FROM user_tab_columns WHERE table_name = 'PLAYERS' AND column_name = 'FULLNAME';
    SELECT COUNT(*) INTO new_count FROM user_tab_columns WHERE table_name = 'PLAYERS' AND column_name = 'FULL_NAME';
    IF old_count = 1 AND new_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE players RENAME COLUMN fullName TO full_name';
    END IF;

    SELECT COUNT(*) INTO old_count FROM user_tab_columns WHERE table_name = 'PLAYERS' AND column_name = 'JERSEYNUMBER';
    SELECT COUNT(*) INTO new_count FROM user_tab_columns WHERE table_name = 'PLAYERS' AND column_name = 'JERSEY_NUMBER';
    IF old_count = 1 AND new_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE players RENAME COLUMN jerseyNumber TO jersey_number';
    END IF;

    SELECT COUNT(*) INTO old_count FROM user_tab_columns WHERE table_name = 'PLAYERS' AND column_name = 'HEALTHSTATUS';
    SELECT COUNT(*) INTO new_count FROM user_tab_columns WHERE table_name = 'PLAYERS' AND column_name = 'HEALTH_STATUS';
    IF old_count = 1 AND new_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE players RENAME COLUMN healthStatus TO health_status';
    END IF;
END;
/

DECLARE
    PROCEDURE add_column_if_missing(column_name_value VARCHAR2, definition_value VARCHAR2) IS
        column_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO column_count
        FROM user_tab_columns
        WHERE table_name = 'PLAYERS' AND column_name = UPPER(column_name_value);
        IF column_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE players ADD (' || definition_value || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('MATCHES', 'matches NUMBER(7) DEFAULT 0 NOT NULL');
    add_column_if_missing('ASSISTS', 'assists NUMBER(7) DEFAULT 0 NOT NULL');
    add_column_if_missing('CLUB', 'club VARCHAR2(100) DEFAULT ''Tự do'' NOT NULL');
    add_column_if_missing('PAC', 'pac NUMBER(3) DEFAULT 70 NOT NULL');
    add_column_if_missing('SHO', 'sho NUMBER(3) DEFAULT 70 NOT NULL');
    add_column_if_missing('PAS', 'pas NUMBER(3) DEFAULT 70 NOT NULL');
    add_column_if_missing('DRI', 'dri NUMBER(3) DEFAULT 70 NOT NULL');
    add_column_if_missing('DEF', 'def NUMBER(3) DEFAULT 70 NOT NULL');
    add_column_if_missing('PHY', 'phy NUMBER(3) DEFAULT 70 NOT NULL');
    add_column_if_missing('CREATED_AT', 'created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL');
    add_column_if_missing('UPDATED_AT', 'updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL');
END;
/

